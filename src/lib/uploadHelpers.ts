/** Client-side helpers to make media uploads much faster. */

/**
 * Downscale + recompress an image in the browser before upload.
 * Large phone photos (5–10 MB) become ~200–500 KB, which is what makes
 * publishing feel instant.
 */
export const compressImage = async (
  file: File,
  maxSize = 1920,
  quality = 0.82
): Promise<File> => {
  if (!file.type.startsWith("image/") || file.type === "image/gif") return file;

  try {
    const bitmap = await createImageBitmap(file);
    const scale = Math.min(1, maxSize / Math.max(bitmap.width, bitmap.height));
    const w = Math.round(bitmap.width * scale);
    const h = Math.round(bitmap.height * scale);

    const canvas = document.createElement("canvas");
    canvas.width = w;
    canvas.height = h;
    const ctx = canvas.getContext("2d");
    if (!ctx) return file;
    ctx.drawImage(bitmap, 0, 0, w, h);
    bitmap.close?.();

    const blob = await new Promise<Blob | null>((resolve) =>
      canvas.toBlob(resolve, "image/jpeg", quality)
    );
    if (!blob || blob.size >= file.size) return file;

    const name = file.name.replace(/\.[^.]+$/, "") + ".jpg";
    return new File([blob], name, { type: "image/jpeg" });
  } catch {
    return file;
  }
};

/** Run async tasks with a bounded concurrency (parallel uploads). */
export const runPool = async <T>(
  tasks: Array<() => Promise<T>>,
  concurrency = 4
): Promise<T[]> => {
  const results: T[] = new Array(tasks.length);
  let next = 0;
  const workers = Array.from({ length: Math.min(concurrency, tasks.length) }, async () => {
    while (next < tasks.length) {
      const i = next++;
      results[i] = await tasks[i]();
    }
  });
  await Promise.all(workers);
  return results;
};
